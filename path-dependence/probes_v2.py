def run(name, spec, n, show_raw=2):
    print(f"\n{'='*64}\nПРОБА {name}  [{spec['tag']}]")
    print(f"контроль извлечения: {spec['control']}")
    dist, raws = {}, {}
    for path in ("P1", "P2"):
        msgs = merge(spec[path]); counts = Counter(); raws[path] = []
        for i in range(n):
            r = call(msgs, 220, GEN_T)
            lab = classify(spec["judge"], spec["labels"], r)
            counts[lab] += 1
            if len(raws[path]) < show_raw:
                raws[path].append((lab, r))
        dist[path] = counts
        print(f"  {path}: {dict(counts)}  (предсказано {spec['predict'][path]})")
    fork = tv_distance(dist["P1"], dist["P2"], spec["labels"])
    p1t, p2t = dist["P1"].most_common(1)[0][0], dist["P2"].most_common(1)[0][0]
    directional = (p1t == spec["predict"]["P1"] and p2t == spec["predict"]["P2"])
    print(f"  FORK-SCORE (TV): {fork:.2f}   направление совпало: {directional}")
    for path in ("P1", "P2"):
        tag = "Вера/смелость/действие первыми" if path == "P1" else "Макс/ответств./бережность первыми"
        print(f"\n  --- сырые {path} ({tag}) ---")
        for lab, r in raws[path]:
            print(f"  [{lab}] {r[:300]}")
    return {"fork": fork, "directional": directional}

def main():
    if not API_KEY:
        print("Нет ANTHROPIC_API_KEY."); return
    n = int(os.environ.get("N", "12"))
    print(f"Модель: {MODEL} | N={n} | темп={GEN_T}")
    summ = {nm: run(nm, sp, n) for nm, sp in PROBES_V2.items()}
    print(f"\n{'#'*64}\nИТОГ (стойко-нагруженные пробы)")
    for nm, r in summ.items():
        v = "ФОРКАЕТ (путь-зависимость есть)" if (r["fork"] >= 0.34 and r["directional"]) \
            else "слабо/не в ту сторону" if r["fork"] >= 0.2 else "ПЛОСКО"
        print(f"  {nm:12s} fork={r['fork']:.2f} dir={r['directional']} -> {v}")

if __name__ == "__main__":
    main()
